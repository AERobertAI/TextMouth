// MARK: - The Adobe Symbol Encoding

/// The characters of the Symbol font, by the code that selects them, as the Unicode Consortium
/// publishes them (`https://www.unicode.org/Public/MAPPINGS/VENDORS/ADOBE/symbol.txt`, version 1.0 of
/// 2011 July 12: "Adobe Symbol Encoding to Unicode"). Word's Insert Symbol stores a character of a font
/// as a code of that font, and the font named Symbol is this encoding. Where the Consortium's table gives
/// a code two Unicode values (space and no-break space, for one) the first is kept. Twenty-nine codes
/// (the pieces of large brackets and braces, the arrow extenders, the copyright and trademark of the
/// serif and sans-serif forms) the table puts in the Corporate Use Subarea: these are private-use
/// scalars, which no voice can speak, and `scalar(forCode:)` gives nil for them.
