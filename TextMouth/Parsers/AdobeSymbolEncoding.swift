    ]

    /// The scalar the code `code` (0 to 255) is, or nil when the encoding defines none or only a
    /// private-use one.
    static func scalar(forCode code: Int) -> Unicode.Scalar? {
        guard table.indices.contains(code), table[code] != 0, let scalar = Unicode.Scalar(table[code]),
              !(0xE000...0xF8FF).contains(table[code]) else { return nil }
        return scalar
    }
}
